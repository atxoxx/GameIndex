/**
 * Persistence helpers for the save-backup engine.
 *
 * `state/db/saves.ts` owns the schema and the row shapes; this module adds the
 * few operations the engine needs that the DAO does not expose yet (lookup by
 * path, deleting a backup index row, stamping a location after a backup or
 * restore). SQL goes through the shared `prepare()` helper so the same cached
 * statements are used everywhere.
 */
import {
  ensureStorage,
  listSaveBackups,
  listSaveLocations,
  prepare,
  upsertSaveLocation,
  type SaveBackup,
  type SaveLocation,
} from "../../state/db";

function randomSuffix(): string {
  return Math.random().toString(36).slice(2, 8);
}

function nowMs(): number {
  return Date.now();
}

/** Comparison key for path de-duplication (case, separator and trailing `/`). */
export function pathKey(value: string): string {
  return value.replace(/\\/g, "/").replace(/\/+$/, "").toLowerCase();
}

export function listLocations(gameId?: string | null): SaveLocation[] {
  ensureStorage("saves");
  const rows = listSaveLocations();
  if (!gameId) return rows;
  return rows.filter((row) => row.gameId === gameId);
}

export function listBackups(gameId?: string | null): SaveBackup[] {
  ensureStorage("saves");
  const rows = listSaveBackups();
  const scoped = gameId ? rows.filter((row) => row.gameId === gameId) : rows;
  return scoped.sort((a, b) => b.createdAt - a.createdAt || b.id.localeCompare(a.id));
}

export function getBackup(id: string): SaveBackup | null {
  return listBackups().find((row) => row.id === id) ?? null;
}

/** Find a stored location for a game by path (case-insensitive). */
export function findLocationByPath(gameId: string, target: string): SaveLocation | null {
  const key = pathKey(target);
  return listLocations(gameId).find((row) => pathKey(row.path) === key) ?? null;
}

/** Insert or update a location, generating an id and timestamps when needed. */
export function upsertLocation(input: SaveLocation): SaveLocation {
  ensureStorage("saves");
  const location: SaveLocation = {
    ...input,
    id: input.id?.trim() ? input.id : `loc-${nowMs()}-${randomSuffix()}`,
    createdAt: input.createdAt && input.createdAt > 0 ? input.createdAt : nowMs(),
    updatedAt: nowMs(),
  };
  upsertSaveLocation(location);
  return location;
}

export function deleteLocation(id: string): number {
  ensureStorage("saves");
  return prepare("saves", "DELETE FROM save_locations WHERE id = ?").run(id).changes;
}

export function deleteLocationsForGame(gameId: string): number {
  ensureStorage("saves");
  return prepare("saves", "DELETE FROM save_locations WHERE game_id = ?").run(gameId).changes;
}

/** Insert a snapshot index row. Ids are generated by the engine. */
export function insertBackup(input: SaveBackup): SaveBackup {
  ensureStorage("saves");
  const backup: SaveBackup = {
    ...input,
    id: input.id?.trim() ? input.id : `bak-${nowMs()}-${randomSuffix()}`,
    createdAt: input.createdAt && input.createdAt > 0 ? input.createdAt : nowMs(),
  };
  prepare(
    "saves",
    `INSERT OR REPLACE INTO save_backups(id, game_id, game_name, created_at, kind, note,
       location_count, file_count, total_bytes, status, error, root_path, manifest_path)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
  ).run(
    backup.id,
    backup.gameId,
    backup.gameName,
    backup.createdAt,
    backup.kind,
    backup.note,
    backup.locationCount,
    backup.fileCount,
    backup.totalBytes,
    backup.status,
    backup.error ?? null,
    backup.rootPath,
    backup.manifestPath,
  );
  return backup;
}

export function deleteBackupRow(id: string): number {
  ensureStorage("saves");
  return prepare("saves", "DELETE FROM save_backups WHERE id = ?").run(id).changes;
}

export function deleteBackupRowsForGame(gameId: string): number {
  ensureStorage("saves");
  return prepare("saves", "DELETE FROM save_backups WHERE game_id = ?").run(gameId).changes;
}

/** Stamp a location as just backed up. */
export function touchLocationBackup(id: string, atMs: number): void {
  ensureStorage("saves");
  prepare(
    "saves",
    "UPDATE save_locations SET last_backup_at = ?, updated_at = ? WHERE id = ?",
  ).run(atMs, atMs, id);
}

/** Stamp a location as just restored. */
export function touchLocationRestore(id: string, atMs: number): void {
  ensureStorage("saves");
  prepare(
    "saves",
    "UPDATE save_locations SET last_restore_at = ?, updated_at = ? WHERE id = ?",
  ).run(atMs, atMs, id);
}
