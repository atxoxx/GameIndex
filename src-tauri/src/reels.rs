// Highlight reels — Tauri commands over the `db::clips` DAO.
//
// v1 scope: registry + playlists only. Clips are file references; reels
// are ordered lists of clip ids. Nothing here copies, trims or encodes
// video, so every command is a small SQL statement and safe to call from
// the UI's hot paths (favorite toggle, drag-to-reorder).

use serde::Deserialize;
use tauri::Manager;

use crate::db::{self, clips::ClipRow, clips::ReelRow, Db};

/// Millisecond wall clock used for `added_at` / `updated_at` stamps.
fn now_ms() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

fn db_of(app: &tauri::AppHandle) -> Db {
    app.state::<Db>().inner().clone()
}

/// Everything the Reels page needs in one round-trip: clips + reels.
#[derive(Debug, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ReelsSnapshot {
    pub clips: Vec<ClipRow>,
    pub reels: Vec<ReelRow>,
}

#[tauri::command]
pub fn reels_get_snapshot(app: tauri::AppHandle) -> Result<ReelsSnapshot, String> {
    let db = db_of(&app);
    Ok(ReelsSnapshot {
        clips: db::clips::list_clips(&db)?,
        reels: db::clips::list_reels(&db)?,
    })
}

/// Payload for `register_clip`. The id is generated by the frontend
/// (`crypto.randomUUID`) so the UI can reference a clip immediately;
/// re-registering a path returns the stored row (which may carry the
/// original id).
#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RegisterClipPayload {
    pub id: String,
    pub path: String,
    pub title: String,
    #[serde(default)]
    pub game_id: Option<String>,
    #[serde(default)]
    pub game_name: Option<String>,
    #[serde(default)]
    pub kind: Option<String>,
    #[serde(default)]
    pub duration_ms: Option<i64>,
    #[serde(default)]
    pub size_bytes: Option<i64>,
    #[serde(default)]
    pub created_at: Option<i64>,
}

#[tauri::command]
pub fn register_clip(app: tauri::AppHandle, clip: RegisterClipPayload) -> Result<ClipRow, String> {
    let db = db_of(&app);
    let stamp = now_ms();
    let row = ClipRow {
        id: clip.id,
        path: clip.path,
        game_id: clip.game_id,
        game_name: clip.game_name,
        title: clip.title,
        kind: clip.kind,
        duration_ms: clip.duration_ms,
        size_bytes: clip.size_bytes,
        favorite: false,
        created_at: clip.created_at.unwrap_or(stamp),
        added_at: stamp,
    };
    db::clips::register_clip(&db, &row)?;
    db::clips::get_clip_by_path(&db, &row.path)?
        .ok_or_else(|| "clip registration lost the row".to_string())
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct UpdateClipPayload {
    pub id: String,
    #[serde(default)]
    pub title: Option<String>,
    #[serde(default)]
    pub favorite: Option<bool>,
    /// `Some(None)` unlinks the game, `Some(Some(id))` relinks it,
    /// `None` leaves it untouched.
    #[serde(default)]
    pub game_id: Option<Option<String>>,
    #[serde(default)]
    pub game_name: Option<Option<String>>,
}

#[tauri::command]
pub fn update_clip(app: tauri::AppHandle, update: UpdateClipPayload) -> Result<(), String> {
    let db = db_of(&app);
    db::clips::update_clip(
        &db,
        &update.id,
        update.title.as_deref(),
        update.favorite,
        update.game_id.as_ref().map(|v| v.as_deref()),
        update.game_name.as_ref().map(|v| v.as_deref()),
    )
}

#[tauri::command]
pub fn delete_clip(app: tauri::AppHandle, id: String) -> Result<(), String> {
    let db = db_of(&app);
    db::clips::delete_clip(&db, &id)
}

#[tauri::command]
pub fn create_reel(
    app: tauri::AppHandle,
    id: String,
    name: String,
    description: Option<String>,
) -> Result<(), String> {
    let db = db_of(&app);
    db::clips::create_reel(&db, &id, &name, description.as_deref(), now_ms())
}

#[tauri::command]
pub fn rename_reel(
    app: tauri::AppHandle,
    id: String,
    name: String,
    description: Option<String>,
) -> Result<(), String> {
    let db = db_of(&app);
    db::clips::rename_reel(&db, &id, &name, description.as_deref(), now_ms())
}

#[tauri::command]
pub fn delete_reel(app: tauri::AppHandle, id: String) -> Result<(), String> {
    let db = db_of(&app);
    db::clips::delete_reel(&db, &id)
}

#[tauri::command]
pub fn add_clip_to_reel(
    app: tauri::AppHandle,
    reel_id: String,
    clip_id: String,
) -> Result<bool, String> {
    let db = db_of(&app);
    db::clips::add_clip_to_reel(&db, &reel_id, &clip_id, now_ms())
}

#[tauri::command]
pub fn remove_clip_from_reel(
    app: tauri::AppHandle,
    reel_id: String,
    clip_id: String,
) -> Result<(), String> {
    let db = db_of(&app);
    db::clips::remove_clip_from_reel(&db, &reel_id, &clip_id, now_ms())
}

#[tauri::command]
pub fn reorder_reel(
    app: tauri::AppHandle,
    reel_id: String,
    clip_ids: Vec<String>,
) -> Result<(), String> {
    let db = db_of(&app);
    db::clips::reorder_reel(&db, &reel_id, &clip_ids, now_ms())
}
